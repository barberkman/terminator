// The `terminator` command, put where a terminal can find it.
//
// Everything lives in one folder, `<userData>/bin`, rewritten each time the app
// starts — as reporter.cjs is, and for the same reasons: the app's own executable
// is the Node that runs it (no node on PATH needed), and a portable build or an
// AppImage runs from somewhere new every launch. It is written whether or not
// Settings → SCRIPTING is on, so that with it off the command is still there to
// say so.
//
//   terminator-cli.js   the command itself (src/cli), copied out of the app bundle
//   terminator.target   the app's exe, that script and this user-data folder, one per line
//   terminator.exe      Windows: the console launcher (launcher-source.ts), compiled here
//   terminator.cmd      Windows: the same, for when it couldn't be compiled
//   terminator          sh: the command on Linux and macOS — and on Windows, for a WSL
//                       distro or Git Bash finding this folder on its PATH
//
// A shell session the app starts gets the folder at the front of its PATH
// (session-launcher.ts). Any other terminal needs it on your PATH, which on Windows
// Settings → SCRIPTING can do for you (`addToPath`).

import { execFile } from 'node:child_process'
import { createHash } from 'node:crypto'
import { chmodSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { delimiter, join } from 'node:path'
import { promisify } from 'node:util'
import { app } from 'electron'
import type { ScriptingInfo } from '../shared/types'
import { LAUNCHER_SOURCE } from './launcher-source'

const pExecFile = promisify(execFile)

/** The folder the command lives in — the one to put on PATH. */
export function commandDir(): string {
  return join(app.getPath('userData'), 'bin')
}

/**
 * The program that runs the command. An AppImage's executable lives on a mount
 * that is gone once the app quits; the AppImage itself is the file to name.
 */
function appExe(): string {
  return process.env.APPIMAGE || process.execPath
}

/** Write only when it changed: another running instance may be reading the old one. */
function put(file: string, content: string | Buffer, mode?: number): void {
  try {
    if (existsSync(file) && readFileSync(file).equals(Buffer.from(content))) return
  } catch {
    // unreadable — write it fresh
  }
  const tmp = `${file}.${process.pid}.tmp`
  writeFileSync(tmp, content, mode === undefined ? undefined : { mode })
  renameSync(tmp, file)
  if (mode !== undefined) chmodSync(file, mode)
}

/** A POSIX shell word: single quotes, with any inside spelled out. */
function q(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`
}

/** cmd.exe has no quoting for `%` inside a batch file, only doubling. */
function batchPath(p: string): string {
  return p.replace(/%/g, '%%')
}

function posixShim(exe: string, cli: string, home: string): string {
  return [
    '#!/bin/sh',
    "# Generated by Terminator: the `terminator` command. Rewritten each time the app starts.",
    `exe=${q(exe)}`,
    `if [ ! -x "$exe" ]; then echo "Terminator isn't running." >&2; exit 1; fi`,
    `ELECTRON_RUN_AS_NODE=1 TERMINATOR_HOME=${q(home)} exec "$exe" ${q(cli)} "$@"`,
    '',
  ].join('\n')
}

/**
 * The same folder seen from a WSL distro (which appends the Windows PATH to its
 * own) or from Git Bash: a shell, not Windows, finds it, and runs this file.
 *
 *   • WSL hands the work to the Windows launcher through interop — the app's port
 *     is on Windows' 127.0.0.1, which a NAT-mode distro can't reach (design/wsl.md).
 *     It says where it is, the distro and the Linux working directory, so a
 *     `--project` given as a Linux path makes a session in that distro, exactly as
 *     picking it under "Run in" would.
 *   • Git Bash rewrites any argument that looks like a path — a prompt starting
 *     `/review` would arrive as `C:/Program Files/Git/review` — so that is turned
 *     off, and the CLI is told where `/` is to read a `--project` itself.
 *
 * Without a compiled launcher both fall back to the app's exe directly, the way
 * Claude's Ctrl+G shim runs it (wslShimSource).
 *
 * WSL runs the Windows program and then exits with its code, rather than `exec`ing
 * it: a Windows program exec'd from a script through WSL 1's interop hands back 0
 * whatever it exited with, and `wait`'s timeout is exit code 2.
 */
function windowsShellShim(exe: string, cli: string, home: string): string {
  return [
    '#!/bin/sh',
    '# Generated by Terminator: the `terminator` command, for a WSL distro or Git Bash on',
    '# Windows. Runs the Windows one beside it. Rewritten each time the app starts.',
    'here=$(cd "$(dirname "$0")" && pwd)',
    `win_exe=${q(exe)}`,
    `win_cli=${q(cli)}`,
    `win_home=${q(home)}`,
    'if [ -n "$WSL_DISTRO_NAME" ]; then',
    '  TERMINATOR_WSL_DISTRO=$WSL_DISTRO_NAME TERMINATOR_WSL_PWD=$PWD',
    '  WSLENV="TERMINATOR_WSL_DISTRO:TERMINATOR_WSL_PWD${WSLENV:+:$WSLENV}"',
    '  export TERMINATOR_WSL_DISTRO TERMINATOR_WSL_PWD WSLENV',
    '  if [ -f "$here/terminator.exe" ]; then "$here/terminator.exe" "$@"; exit $?; fi',
    '  exe=$(wslpath -u "$win_exe" 2>/dev/null)',
    '  ELECTRON_RUN_AS_NODE=1 TERMINATOR_HOME=$win_home',
    '  WSLENV="ELECTRON_RUN_AS_NODE:TERMINATOR_HOME:$WSLENV"',
    '  export ELECTRON_RUN_AS_NODE TERMINATOR_HOME WSLENV',
    `  if [ ! -f "$exe" ]; then echo "Terminator isn't running." >&2; exit 1; fi`,
    '  "$exe" "$win_cli" "$@"',
    '  exit $?',
    'fi',
    'MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL="*"',
    'TERMINATOR_MSYS_ROOT=$(cygpath -w / 2>/dev/null)',
    'export MSYS_NO_PATHCONV MSYS2_ARG_CONV_EXCL TERMINATOR_MSYS_ROOT',
    'if [ -f "$here/terminator.exe" ]; then exec "$here/terminator.exe" "$@"; fi',
    `if [ ! -f "$win_exe" ]; then echo "Terminator isn't running." >&2; exit 1; fi`,
    'ELECTRON_RUN_AS_NODE=1 TERMINATOR_HOME=$win_home exec "$win_exe" "$win_cli" "$@"',
    '',
  ].join('\n')
}

function cmdShim(exe: string, cli: string, home: string): string {
  return [
    '@echo off',
    'rem Generated by Terminator: the `terminator` command, for when terminator.exe',
    'rem could not be built. Rewritten each time the app starts.',
    'setlocal',
    'set "ELECTRON_RUN_AS_NODE=1"',
    `set "TERMINATOR_HOME=${batchPath(home)}"`,
    `if not exist "${batchPath(exe)}" (`,
    "  echo Terminator isn't running. 1>&2",
    '  exit /b 1',
    ')',
    `"${batchPath(exe)}" "${batchPath(cli)}" %*`,
    'exit /b %ERRORLEVEL%',
    '',
  ].join('\r\n')
}

/**
 * Build terminator.exe with the C# compiler in Windows' own .NET Framework folder,
 * when it's missing or its source changed. In the background: nothing waits on it,
 * and until it lands — or if it never can — terminator.cmd answers instead.
 */
async function buildLauncher(dir: string): Promise<void> {
  const exe = join(dir, 'terminator.exe')
  const stamp = join(dir, 'terminator.exe.source')
  const hash = createHash('sha256').update(LAUNCHER_SOURCE).digest('hex')
  try {
    if (existsSync(exe) && readFileSync(stamp, 'utf8') === hash) return
  } catch {
    // no stamp: build
  }
  const windir = process.env.WINDIR || process.env.SystemRoot || 'C:\\Windows'
  const csc = ['Framework64', 'Framework']
    .map((f) => join(windir, 'Microsoft.NET', f, 'v4.0.30319', 'csc.exe'))
    .find((p) => existsSync(p))
  if (!csc) return
  const src = join(dir, `terminator-launcher.${process.pid}.cs`)
  const out = join(dir, `terminator.${process.pid}.exe`)
  try {
    writeFileSync(src, LAUNCHER_SOURCE, 'utf8')
    await pExecFile(csc, ['/nologo', '/optimize+', '/target:exe', `/out:${out}`, src], {
      windowsHide: true,
      timeout: 60_000,
    })
    // Fails while a running `terminator` holds the old one; the next start retries.
    renameSync(out, exe)
    writeFileSync(stamp, hash, 'utf8')
  } catch {
    // terminator.cmd still works
  } finally {
    rmSync(src, { force: true })
    rmSync(out, { force: true })
  }
}

/** Write the command's folder afresh. Called once at startup, before any shell session can start. */
export function installCommand(): void {
  const dir = commandDir()
  try {
    mkdirSync(dir, { recursive: true })
    const cli = join(dir, 'terminator-cli.js')
    // Read out of the app bundle (asar reads work here, in main) and written as a
    // real file, so the Node-mode exe never has to look inside the archive.
    put(cli, readFileSync(join(__dirname, 'cli.js')))
    const home = app.getPath('userData')
    const exe = appExe()
    put(join(dir, 'terminator.target'), [exe, cli, home].join('\r\n') + '\r\n')
    if (process.platform === 'win32') {
      put(join(dir, 'terminator.cmd'), cmdShim(exe, cli, home))
      put(join(dir, 'terminator'), windowsShellShim(exe, cli, home), 0o755)
      void buildLauncher(dir)
    } else {
      put(join(dir, 'terminator'), posixShim(exe, cli, home), 0o755)
    }
  } catch (e) {
    console.error('[terminator] could not install the command:', e)
  }
}

/** Expand `%NAME%` the way Windows does when it reads a REG_EXPAND_SZ PATH. */
function expandWin(p: string): string {
  return p.replace(/%([^%]+)%/g, (m, name: string) => {
    const key = Object.keys(process.env).find((k) => k.toUpperCase() === name.toUpperCase())
    return key ? (process.env[key] ?? m) : m
  })
}

function samePath(a: string, b: string): boolean {
  const norm = (p: string): string => p.replace(/[\\/]+$/, '')
  return process.platform === 'win32' ? norm(a).toLowerCase() === norm(b).toLowerCase() : norm(a) === norm(b)
}

/** Your user PATH as stored (Windows), unexpanded; empty when there isn't one. */
async function userPath(): Promise<string> {
  try {
    const { stdout } = await pExecFile('reg', ['query', 'HKCU\\Environment', '/v', 'Path'], { windowsHide: true })
    const m = /^\s*Path\s+REG_(?:EXPAND_)?SZ\s+(.*)$/im.exec(stdout)
    return m ? m[1].trim() : ''
  } catch {
    // no Path value yet
    return ''
  }
}

export async function scriptingInfo(): Promise<ScriptingInfo> {
  const dir = commandDir()
  if (process.platform !== 'win32') {
    const onPath = (process.env.PATH ?? '').split(delimiter).some((p) => samePath(p, dir))
    return { dir, onPath, canAddToPath: false }
  }
  const onPath = (await userPath())
    .split(';')
    .filter(Boolean)
    .some((p) => samePath(expandWin(p), dir))
  return { dir, onPath, canAddToPath: true }
}

/**
 * Add the command's folder to the end of your user PATH. Written back raw, as an
 * expandable string, so the `%USERPROFILE%`-style entries already there stay
 * entries rather than being frozen into today's paths — `setx` and .NET's own
 * setter both expand them. Then the dummy-variable write makes .NET announce the
 * change, so terminals opened from now on pick it up.
 */
export async function addToPath(): Promise<ScriptingInfo & { error?: string }> {
  if (process.platform !== 'win32') return { ...(await scriptingInfo()), error: 'add the folder to PATH yourself here' }
  const dir = commandDir()
  const script = [
    `$dir = '${dir.replace(/'/g, "''")}'`,
    "$key = [Microsoft.Win32.Registry]::CurrentUser.OpenSubKey('Environment', $true)",
    "$cur = [string]$key.GetValue('Path', '', 'DoNotExpandEnvironmentNames')",
    "$parts = @($cur -split ';' | Where-Object { $_ -ne '' })",
    "$have = $parts | Where-Object { [Environment]::ExpandEnvironmentVariables($_).TrimEnd('\\') -ieq $dir.TrimEnd('\\') }",
    "if (-not $have) { $key.SetValue('Path', (@($parts) + $dir) -join ';', [Microsoft.Win32.RegistryValueKind]::ExpandString) }",
    '$key.Close()',
    "[Environment]::SetEnvironmentVariable('TERMINATOR_PATH_REFRESH', $null, 'User')",
  ].join('\n')
  try {
    await pExecFile('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', script], {
      windowsHide: true,
      timeout: 30_000,
    })
  } catch (e) {
    return { ...(await scriptingInfo()), error: (e instanceof Error ? e.message : String(e)).slice(0, 200) }
  }
  return scriptingInfo()
}
